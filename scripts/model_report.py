"""
Generate docs/MODEL_CARD.md from the model registry so documented metrics are
always the stored evaluation results (never hand-typed).

Run: python scripts/model_report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy import text  # noqa: E402

from common.db import get_engine  # noqa: E402
from ml_core.models.feature_catalog import describe  # noqa: E402


def pct(value, digits=2):
    return "n/a" if value is None else f"{value * 100:.{digits}f}%"


def num(value, digits=4):
    return "n/a" if value is None else f"{value:.{digits}f}"


def main() -> None:
    with get_engine().connect() as conn:
        models = conn.execute(text(
            """
            SELECT DISTINCT ON (horizon_days) id, horizon_days, version, status, trained_at, train_start, train_end,
                   data_end, metrics, calibration, feature_importance, params, data_hash, code_version, notes
            FROM model_registry WHERE model_name = 'xgb_forecaster'
            ORDER BY horizon_days, (status = 'active') DESC, trained_at DESC
            """
        )).mappings().all()
        challenger = conn.execute(text(
            "SELECT version, metrics, notes FROM model_registry WHERE model_name = 'tft_challenger' ORDER BY trained_at DESC LIMIT 1"
        )).mappings().one_or_none()

    lines = [
        "# Model card — multi-horizon XGBoost forecaster",
        "",
        "_Generated by `scripts/model_report.py` from the model registry; do not edit numbers by hand._",
        "",
        "## Intended use",
        "",
        "Ranking and sizing inputs for a CVaR-constrained, long-only portfolio of 12 liquid US assets, and",
        "explanations for research. Not a standalone trading signal and not investment advice.",
        "",
        "## Design",
        "",
        "* Targets: future total return over 1, 5 and 21 trading days (t+1…t+h, dividends included) and",
        "  realised volatility over the next max(h, 5) days.",
        "* Mean model: XGBoost on the cross-sectionally demeaned return plus a historical universe-mean prior;",
        "  strong regularisation (depth 3, min child weight 300, λ=20, 200 rounds, η=0.02).",
        "* Uncertainty: 5/50/95% quantile XGBoost + split-conformal adjustment on a purged calibration window → 90% interval.",
        "* Volatility: XGBoost on log realised volatility with smearing correction; baseline = trailing 20-day volatility.",
        "* Validation: expanding walk-forward, refit every 63 trading days, purge = horizon, embargo = 5 days;",
        "  the configuration was chosen among 4 candidates using folds with test dates before 2020 only.",
        "* Explanations: exact TreeSHAP (`pred_contribs`) of the mean model; contributions sum to the forecast.",
        "",
        "## Out-of-sample results",
        "",
        "| Metric | " + " | ".join(f"{m['horizon_days']}-day" for m in models) + " |",
        "|---|" + "---|" * len(models),
    ]

    def row(label, getter):
        lines.append(f"| {label} | " + " | ".join(getter(m["metrics"] or {}) for m in models) + " |")

    row("Status / version", lambda m: "")
    lines[-1] = "| Status / version | " + " | ".join(f"{m['status']} `{m['version']}`" for m in models) + " |"
    row("OOS predictions", lambda m: f"{m.get('observations', 0):,}")
    row("OOS window", lambda m: f"{m.get('test_start')} → {m.get('test_end')}")
    row("Rank IC (mean, daily)", lambda m: num(m.get("ic_mean")))
    row("IC t-stat (overlap-adjusted)", lambda m: num(m.get("ic_tstat_overlap_adjusted"), 2))
    row("IC hit rate", lambda m: pct(m.get("ic_hit_rate"), 1))
    row("Top−bottom tercile spread", lambda m: pct(m.get("top_minus_bottom_tercile_return"), 3))
    row("MAE / zero-forecast MAE", lambda m: f"{pct(m.get('mae'), 3)} / {pct(m.get('mae_zero_baseline'), 3)}")
    row("OOS R² vs zero forecast", lambda m: num(m.get("r2_oos_vs_zero")))
    row("Directional accuracy (base rate up)", lambda m: f"{pct(m.get('directional_accuracy'), 1)} ({pct(m.get('base_rate_positive'), 1)})")
    row("90% interval coverage (width)", lambda m: f"{pct(m.get('interval_coverage'), 1)} ({pct(m.get('interval_mean_width'), 1)})")
    row("Vol MAE / trailing-20d baseline", lambda m: f"{pct(m.get('vol_mae'))} / {pct(m.get('vol_mae_trailing20d_baseline'))}")
    row("Holdout ≥2020: IC (t)", lambda m: f"{num((m.get('holdout_since_2020') or {}).get('ic_mean'))} ({num((m.get('holdout_since_2020') or {}).get('ic_tstat_overlap_adjusted'), 2)})")
    row("Holdout ≥2020: R² vs zero", lambda m: num((m.get("holdout_since_2020") or {}).get("r2_oos_vs_zero")))
    row("Holdout ≥2020: coverage", lambda m: pct((m.get("holdout_since_2020") or {}).get("interval_coverage"), 1))

    lines += ["", "### Rank IC by year", "", "| Year | " + " | ".join(f"{m['horizon_days']}d" for m in models) + " |",
              "|---|" + "---|" * len(models)]
    years = sorted({y for m in models for y in ((m["metrics"] or {}).get("ic_by_year") or {})})
    for year in years:
        lines.append(f"| {year} | " + " | ".join(num(((m["metrics"] or {}).get("ic_by_year") or {}).get(year)) for m in models) + " |")

    for model in models:
        importance = list((model["feature_importance"] or {}).items())[:10]
        lines += ["", f"### Top features, {model['horizon_days']}-day model (mean |SHAP|, last 12 months)", ""]
        lines += [f"{i}. {describe(name)['label']} ({describe(name)['group']}) — {value * 100:.1f}%" for i, (name, value) in enumerate(importance, 1)]
        calibration = model["calibration"] or {}
        lines += ["", f"Calibration: reliability slope {num(calibration.get('reliability_slope'), 2)} "
                      f"(realised vs forecast; 1 = well scaled). Gate notes: {model['notes'] or 'passed all promotion gates'}.",
                  f"Lineage: trained {model['trained_at']}, labels {model['train_start']} → {model['train_end']}, "
                  f"data hash `{model['data_hash']}`, code `{model['code_version']}`."]

    lines += ["", "## Temporal Fusion Transformer challenger", ""]
    if challenger:
        metrics = challenger["metrics"] or {}
        tft, xgb = metrics.get("tft") or {}, metrics.get("xgboost") or {}
        lines += [
            f"Version `{challenger['version']}`, holdout {metrics.get('test_start')} → {metrics.get('test_end')}, "
            f"{metrics.get('observations')} identical (ticker, date) rows.",
            "",
            "| Metric | TFT | XGBoost (active) |",
            "|---|---|---|",
            *[f"| {key} | {num(tft.get(key))} | {num(xgb.get(key))} |" for key in ("ic_mean", "mae", "r2_oos_vs_zero", "directional_accuracy")],
            "",
            challenger["notes"] or "",
        ]
    else:
        lines.append("Not yet trained.")

    lines += ["", "## Interpretation", "",
              "Short-horizon equity return predictability is weak and unstable; treat these forecasts as noisy",
              "tilts. The portfolio layer scales them by demonstrated holdout skill (IC t-stat / 3, capped at 1) and",
              "enforces risk limits independently of forecast quality. See LIMITATIONS.md."]
    (ROOT / "docs" / "MODEL_CARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("docs/MODEL_CARD.md written for horizons", [m["horizon_days"] for m in models])


if __name__ == "__main__":
    main()
