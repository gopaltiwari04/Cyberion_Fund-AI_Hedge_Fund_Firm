"""
Recommendation engine shared by the API (personalised) and the daily house-portfolio job.

Inputs: a holdings book (shares per ticker + cash) and risk preferences.
Steps:
    1. latest live forecasts + SHAP explanations of the active model (from DB)
    2. current weights from latest prices
    3. CVaR-constrained optimisation (ml_core.portfolio.optimizer)
    4. trade list (value and share deltas) with per-asset explanations
    5. P/L scenarios for current vs. proposed portfolios:
         - model-based expected P/L with a Gaussian 90% band
         - historical distribution of rolling h-day returns (empirical percentiles)
         - stress replays of named historical episodes
All numbers are computed from stored data; nothing is simulated or invented.
"""

from __future__ import annotations

from dataclasses import replace
from datetime import date

import numpy as np
import pandas as pd
from sqlalchemy import text

from common.db import get_engine
from common.serialization import to_builtin
from common.universe import asset_lookup, tickers as universe_tickers
from ml_core.portfolio.market import alpha_confidence, latest_prices, return_scenarios, risk_free_daily
from ml_core.portfolio.optimizer import CASH, OptimizationConstraints, OptimizationInput, optimize_portfolio

MODEL_NAME = "xgb_forecaster"
DEFAULT_HORIZON = 5

RISK_PROFILES: dict[str, OptimizationConstraints] = {
    "conservative": OptimizationConstraints(risk_aversion=10, cvar_limit=0.015, max_weight=0.20, max_sector_weight=0.40, min_cash=0.05),
    "balanced": OptimizationConstraints(risk_aversion=5, cvar_limit=0.025, max_weight=0.30, max_sector_weight=0.60),
    "aggressive": OptimizationConstraints(risk_aversion=2, cvar_limit=0.040, max_weight=0.40, max_sector_weight=0.80),
}

STRESS_EPISODES = [
    ("Q4 2018 sell-off", date(2018, 9, 20), date(2018, 12, 24)),
    ("COVID-19 crash", date(2020, 2, 19), date(2020, 3, 23)),
    ("2022 rate shock", date(2022, 1, 3), date(2022, 10, 12)),
    ("March 2023 bank stress", date(2023, 3, 8), date(2023, 3, 17)),
    ("April 2025 tariff shock", date(2025, 4, 2), date(2025, 4, 8)),
]

DISCLAIMER = (
    "Educational decision-support output generated by statistical models. It is not personalised investment "
    "advice, not an offer or solicitation, and forecasts are uncertain estimates rather than guaranteed returns. "
    "Past performance and backtests do not guarantee future results. Consult a licensed professional before investing."
)


def constraints_for(profile: str, **overrides) -> OptimizationConstraints:
    if profile not in RISK_PROFILES:
        raise ValueError(f"Unknown risk profile: {profile}")
    clean = {key: value for key, value in overrides.items() if value is not None}
    return replace(RISK_PROFILES[profile], **clean)


def load_forecasts(horizon: int) -> tuple[pd.DataFrame, dict | None]:
    with get_engine().connect() as conn:
        model = conn.execute(
            text(
                """
                SELECT id, version, metrics, trained_at, data_end FROM model_registry
                WHERE model_name = :name AND horizon_days = :h AND status = 'active'
                ORDER BY trained_at DESC LIMIT 1
                """
            ),
            {"name": MODEL_NAME, "h": horizon},
        ).mappings().one_or_none()
        if model is None:
            return pd.DataFrame(), None
        frame = pd.read_sql(
            text(
                """
                SELECT ticker, as_of_date, pred_return, pred_lower, pred_upper, interval_level, pred_volatility, explanation
                FROM model_predictions
                WHERE model_id = :id AND kind = 'live'
                  AND as_of_date = (SELECT MAX(as_of_date) FROM model_predictions WHERE model_id = :id AND kind = 'live')
                """
            ),
            conn,
            params={"id": model["id"]},
        )
    return frame, dict(model)


def portfolio_path_return(returns: pd.DataFrame, weights: dict[str, float]) -> pd.Series:
    risky = {t: w for t, w in weights.items() if t != CASH and w > 0}
    if not risky:
        return pd.Series(0.0, index=returns.index)
    return returns[list(risky)].fillna(0.0) @ np.array(list(risky.values()))


def scenario_analysis(weights: dict[str, float], value: float, horizon: int, expected: float, vol_horizon: float,
                      history: pd.DataFrame) -> dict:
    daily = portfolio_path_return(history, weights)
    rolling = (1 + daily).rolling(horizon).apply(np.prod, raw=True).dropna() - 1
    percentiles = {f"p{p}": float(np.percentile(rolling, p)) * value for p in (5, 25, 50, 75, 95)} if len(rolling) else {}
    stresses = []
    for name, start, end in STRESS_EPISODES:
        window = daily[(daily.index >= pd.Timestamp(start)) & (daily.index <= pd.Timestamp(end))]
        covered = [t for t, w in weights.items() if t != CASH and w > 0 and history.loc[window.index, t].notna().all()] if len(window) else []
        if len(window) < 2 or len(covered) < len([t for t, w in weights.items() if t != CASH and w > 0]):
            stresses.append({"name": name, "start": str(start), "end": str(end), "return": None, "pnl": None,
                             "note": "insufficient history for all holdings"})
            continue
        cumulative = float(np.prod(1 + window.to_numpy()) - 1)
        stresses.append({"name": name, "start": str(start), "end": str(end), "return": cumulative, "pnl": cumulative * value})
    return {
        "model_expected_pnl": expected * value,
        "model_band_90": [(expected - 1.645 * vol_horizon) * value, (expected + 1.645 * vol_horizon) * value],
        "historical_horizon_pnl_percentiles": percentiles,
        "historical_window": {"start": str(history.index.min().date()), "end": str(history.index.max().date()),
                              "observations": int(len(rolling))},
        "stress_tests": stresses,
    }


def build_recommendation(holdings: dict[str, float], cash: float, profile: str = "balanced",
                         horizon: int = DEFAULT_HORIZON, constraint_overrides: dict | None = None,
                         treat_as_weights: bool = False) -> dict:
    """
    holdings: shares per ticker (or weights if treat_as_weights); cash in currency units (or weight).
    """
    constraints = constraints_for(profile, **(constraint_overrides or {}))
    assets = asset_lookup()
    forecasts, model = load_forecasts(horizon)
    if model is None or forecasts.empty:
        return {"status": "unavailable", "message": "No active forecasting model with live predictions is available yet.",
                "disclaimer": DISCLAIMER}

    available = [t for t in universe_tickers() if t in set(forecasts["ticker"])]
    forecasts = forecasts.set_index("ticker").loc[available]
    prices = latest_prices(available)
    unknown = sorted(set(holdings) - set(available))
    if unknown:
        raise ValueError(f"Holdings contain tickers outside the supported universe: {unknown}")

    if treat_as_weights:
        value = 1.0
        current_values = {t: float(holdings.get(t, 0.0)) for t in available}
        cash_value = float(cash)
    else:
        current_values = {t: float(holdings.get(t, 0.0)) * prices[t]["close"] for t in available}
        cash_value = float(cash)
        value = cash_value + sum(current_values.values())
    has_book = value > 0
    if not has_book:
        value = 1.0
    current_weights = np.array([current_values[t] / value for t in available]) if has_book else None

    history = return_scenarios(available, window=2900)  # full history for stress tests
    scenarios = history.tail(756)
    as_of = pd.Timestamp(forecasts["as_of_date"].iloc[0]).date()
    rf_daily, rf_source = risk_free_daily(as_of)
    confidence = alpha_confidence(model["metrics"])

    result = optimize_portfolio(
        OptimizationInput(
            tickers=available,
            expected_returns=forecasts["pred_return"].to_numpy(dtype=float),
            horizon_days=horizon,
            scenarios=scenarios.to_numpy(),
            sectors=[assets[t].sector for t in available],
            current_weights=current_weights,
            risk_free_daily=rf_daily,
            alpha_confidence=confidence,
        ),
        constraints,
    )

    current_weight_map = {t: (current_values[t] / value if has_book else 0.0) for t in available}
    current_weight_map[CASH] = (cash_value / value) if has_book else 1.0

    assets_out = []
    for ticker in available:
        row = forecasts.loc[ticker]
        target = result.weights.get(ticker, 0.0) if result.weights else None
        current_w = current_weight_map[ticker]
        trade_value = (target - current_w) * value if target is not None else None
        price = prices[ticker]["close"]
        assets_out.append(
            {
                "ticker": ticker,
                "name": assets[ticker].name,
                "sector": assets[ticker].sector,
                "price": price,
                "price_date": str(prices[ticker]["date"]),
                "current_weight": current_w,
                "target_weight": target,
                "trade_value": trade_value,
                "trade_shares": (trade_value / price) if trade_value is not None and not treat_as_weights else None,
                "action": None if target is None else ("buy" if trade_value > value * 1e-4 else "sell" if trade_value < -value * 1e-4 else "hold"),
                "forecast": {
                    "horizon_days": horizon,
                    "expected_return": float(row["pred_return"]),
                    "interval": [float(row["pred_lower"]), float(row["pred_upper"])],
                    "interval_level": float(row["interval_level"]),
                    "volatility_annualized": float(row["pred_volatility"]) if pd.notna(row["pred_volatility"]) else None,
                },
                "risk_contribution": (result.metrics.get("risk_contribution") or {}).get(ticker),
                "explanation": row["explanation"],
            }
        )

    proposal = {"weights": result.weights, "metrics": result.metrics} if result.feasible else None
    current_eval = None
    if has_book:
        current_eval = scenario_analysis(
            current_weight_map, value, horizon,
            float(sum(current_weight_map[t] * forecasts.loc[t, "pred_return"] for t in available)),
            float(np.sqrt(max(np.array([current_weight_map[t] for t in available]) @ np.cov(scenarios.to_numpy(), rowvar=False)
                              @ np.array([current_weight_map[t] for t in available]), 0.0)) * np.sqrt(horizon)),
            history,
        )
    proposed_eval = None
    if result.feasible:
        proposed_eval = scenario_analysis(
            result.weights, value, horizon, result.metrics["expected_return_horizon"],
            result.metrics["volatility_horizon"], history,
        )

    return to_builtin({
        "status": result.status,
        "feasible": result.feasible,
        "message": result.message,
        "as_of_date": str(as_of),
        "portfolio_value": value if has_book else None,
        "profile": profile,
        "constraints": constraints.__dict__,
        "model": {
            "id": model["id"], "version": model["version"], "horizon_days": horizon,
            "trained_at": str(model["trained_at"]), "data_end": str(model["data_end"]),
            "alpha_confidence": confidence,
            "holdout_ic": (model["metrics"] or {}).get("holdout_since_2020", {}).get("ic_mean"),
        },
        "risk_free": {"daily": rf_daily, "source": rf_source},
        "current_weights": current_weight_map,
        "proposal": proposal,
        "assets": assets_out,
        "binding_constraints": result.binding_constraints,
        "diagnostics": result.diagnostics,
        "assumptions": result.assumptions,
        "scenarios": {"current": current_eval, "proposed": proposed_eval},
        "disclaimer": DISCLAIMER,
    })
